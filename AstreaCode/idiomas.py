def nome_inimigo_localizado(tipo, bioma_id, idioma_atual="PT"):
    idioma = idioma_atual if idioma_atual in ("PT", "EN", "ES") else "PT"
    indice = max(1, min(15, int(bioma_id))) - 1
    papel = tipo if tipo in _PAPEIS_INIMIGOS else "melee"
    if papel in ("trapper", "duelist"):
        bioma = nome_bioma_localizado(indice + 1, idioma)
        nomes = {
            "PT": ("Armadilheiro de", "Duelista de"),
            "EN": ("", ""),
            "ES": ("Trampero de", "Duelista de"),
        }
        prefixos = nomes[idioma]
        if idioma == "EN":
            return f"{bioma} {'Trapper' if papel == 'trapper' else 'Duelist'}"
        return f"{prefixos[0 if papel == 'trapper' else 1]} {bioma}"
    if idioma == "PT":
        from config import BIOMAS_INIMIGOS

        return BIOMAS_INIMIGOS.get(indice + 1, BIOMAS_INIMIGOS[1]).get(
            papel, BIOMAS_INIMIGOS[1]["melee"]
        )
    if papel in ("assassin", "bomber"):
        return _NOMES_INIMIGOS_EXTRAS[idioma][papel][indice]
    return _NOMES_INIMIGOS[idioma][indice][_PAPEIS_INIMIGOS.index(papel)]


