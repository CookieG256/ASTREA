def _substitute(match, replacements):
    source = match.group(0)
    translated = replacements.get(source.casefold(), source)
    if source.isupper():
        return translated.upper()
    if source[:1].isupper():
        return translated[:1].upper() + translated[1:]
    return translated


def _localize(text, idioma):
    if not isinstance(text, str) or not text:
        return text
    phrases = _PHRASES[idioma]
    for source in sorted(phrases, key=len, reverse=True):
        text = re.sub(re.escape(source), phrases[source], text, flags=re.IGNORECASE)
    return _WORD_RE[idioma].sub(
        lambda match: _substitute(match, _WORDS[idioma]), text
    )


def traduzir_item_index(item, idioma) -> tuple[str, str]:
    """Return an index item's localized name and description, in that order.

    Portuguese, unsupported languages, and absent fields are returned
    unchanged. The input item is never modified.
    """
    nome = item.get("nome", "")
    desc = item.get("desc", "")
    idioma = idioma.upper() if isinstance(idioma, str) else idioma
    if idioma not in _PHRASES:
        return nome, desc

    return (
        _NAME_OVERRIDES[idioma].get(nome, _localize(nome, idioma))
        if isinstance(nome, str) else nome,
        _localize(desc, idioma) if isinstance(desc, str) else desc,
    )
